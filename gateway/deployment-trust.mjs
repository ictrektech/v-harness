/**
 * The deployment's plugin trust declaration, derived per launch.
 *
 * v-harness serves every tenant through the gateway's authenticated proxy: the
 * tenant's own loopback never serves a browser, and the tenant launches with
 * `--trusted-host 127.0.0.1:<port>`, so each authenticated page is already an
 * owner Peer through DSH's own fence. The plugin ecosystem's second trust
 * channel is per-plugin config: an entry whose `config` declares the
 * `remoteAccess` field gates remote management on `trusted-host` and defaults
 * to `read-only` — the right default for a desktop that trusts its own
 * loopback, and the wrong one for a remote deployment whose trust boundary is
 * the gateway identity gate.
 *
 * Patching each plugin by hand does not scale and does not survive upgrades: a
 * static row replaces a whole config, so it either restates the plugin's
 * versioned defaults (drifting on every release) or drops them. Instead, every
 * launch derives the declaration from the installed packages themselves:
 * each package's bundle layer (`cordis.patch.yml`) is scanned for entries that
 * declare `remoteAccess`, and the overlay restates that entry's own config
 * with the value changed to `trusted-host`. A plugin upgrade — image payload
 * or a tenant's own market install — re-derives its row on the next launch; a
 * plugin without the field is untouched.
 *
 * The output is a loader patch list (`--patch`), one top-level row per entry —
 * the shape each plugin's own installation guide prescribes for profile
 * overrides. Rows are deduplicated per entry id (the copy dsh actually
 * resolves wins) and sorted by id, so journal-routed settings changes stay
 * aligned with their rows.
 *
 * The overlay is not tracked by last-good: it is a pure function of what is
 * installed, never a record of what a tenant chose, and the next launch
 * rewrites it wholesale.
 *
 * Debug: `node gateway/deployment-trust.mjs <payloadRoot> [out]` derives and
 * prints/writes the rows one payload root yields.
 *
 * @module v-harness/gateway/deployment-trust
 */

import { execFile } from 'node:child_process';
import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';

import { AGENT_PLUGIN_ROOT } from './plugins.mjs';

/** Where the overlay lives inside one tenant home. */
const PATCH_RELATIVE = join('.dsh', 'profiles', 'web', 'trust.patch.yml');

/** The launch argv carries the overlay only while this switch is not off. */
const TRUST_ENV = 'VH_TRUSTED_REMOTE';

/** The dsh deployment the image ships; the gateway's parser comes from there. */
const DEFAULT_DSH_BIN = '/usr/local/lib/node_modules/@deepseek-ai/dsh/lib/bin.js';

const HEADER = `# Generated by the v-harness gateway from the installed plugin bundles.
# v-harness authenticates every tenant at the gateway, so a remote page is a
# trusted deployment client: entries that declare the plugin ecosystem's
# remoteAccess field are restated as trusted-host, cloned from the entry's own
# config. Do not edit; the next launch replaces this file.`;

// The gateway ships without node_modules of its own. The image's dsh
// deployment closure carries js-yaml (the loader include parses patch files
// with it); a checkout resolves the workspace dev dependency instead.
let yaml;
{
  const closurePath = join(
    dirname(process.env.DSH_BIN ?? DEFAULT_DSH_BIN),
    '..', 'node_modules', 'js-yaml', 'index.js',
  );
  yaml = (await import(pathToFileURL(closurePath).href).catch(() => import('js-yaml'))).default;
}

/** A `!!js` expression value, loaded only to be detected and refused. */
class JsExpr {}

/** Bundle patches may carry loader expressions; parse but never restate them. */
const BUNDLE_SCHEMA = yaml.DEFAULT_SCHEMA.extend(new yaml.Type('tag:yaml.org,2002:js', {
  kind: 'scalar',
  resolve: (data) => typeof data === 'string',
  construct: (data) => new JsExpr(data),
}));

function isPlainObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function containsJsExpr(value) {
  if (value instanceof JsExpr) return true
  if (Array.isArray(value)) return value.some(containsJsExpr)
  if (isPlainObject(value)) return Object.values(value).some(containsJsExpr)
  return false
}

function plainClone(value) {
  if (Array.isArray(value)) return value.map(plainClone)
  if (isPlainObject(value)) {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, plainClone(item)]))
  }
  return value
}

/**
 * The trust rows one bundle patch document yields.
 * @param {string} text - the package's `cordis.patch.yml`.
 * @param {string} packageName - the package the bundle belongs to, for reports.
 * @returns {{ id: string, name: string, config: Record<string, unknown> }[]}
 */
export function trustRows(text, packageName) {
  const doc = yaml.load(text, { schema: BUNDLE_SCHEMA })
  if (!Array.isArray(doc)) return []
  /** @type {{ id: string, name: string, config: Record<string, unknown> }[]} */
  const rows = []
  const walkEntries = (entries) => {
    for (const entry of entries) {
      if (!isPlainObject(entry)) continue
      // A group's children are entries in their own right; the group itself
      // carries no config the loader would mount.
      if (entry.group === true && Array.isArray(entry.config)) {
        walkEntries(entry.config)
        continue
      }
      const { config } = entry
      if (!isPlainObject(config) || config.remoteAccess === undefined) continue
      if (config.remoteAccess === 'trusted-host') continue
      if (typeof entry.id !== 'string' || typeof entry.name !== 'string') {
        throw new Error(`${packageName}: entry declaring remoteAccess lacks an id or name`)
      }
      if (containsJsExpr(config)) {
        throw new Error(
          `${packageName}: entry ${entry.id} restates its config with !!js expressions,`
          + ' which the trust overlay cannot carry; set remoteAccess: trusted-host'
          + ' in the bundle itself',
        )
      }
      rows.push({ id: entry.id, name: entry.name, config: { ...plainClone(config), remoteAccess: 'trusted-host' } })
    }
  }
  // A bundle layer is a patch list: its entries arrive inside `insert` ops,
  // addressed at a parent group or at the composition root.
  for (const patch of doc) {
    if (!isPlainObject(patch)) continue
    if (Array.isArray(patch.insert)) walkEntries(patch.insert)
  }
  return rows
}

/**
 * Whether a generated document is a patch list the launcher accepts.
 * Asserted before the file is handed to `--patch`: a malformed overlay is not
 * a small mistake, it is a workspace that never boots.
 * @param {string} text - the document about to be written.
 * @returns {boolean}
 */
export function isTrustPatch(text) {
  const lines = text.split('\n').filter((line) => line !== '' && !line.startsWith('#'))
  if (lines.length === 1 && lines[0] === '[]') return true
  if (lines.length === 0 || !lines[0].startsWith('- id: ')) return false
  // Row starts sit at column zero; everything a row carries is indented, and
  // nested config may indent arbitrarily deep.
  return lines.every((line) => /^- id: [^\s]+$/.test(line) || /^ {2,}\S/.test(line))
}

/**
 * The patch document for the trust rows: the header plus the row list, or the
 * empty list when nothing declares the field — the launcher takes an empty
 * patch and the launch argv stays uniform.
 * @param {{ id: string, name: string, config: Record<string, unknown> }[]} rows
 * @returns {string}
 */
export function trustPatchDoc(rows) {
  const body = rows.length === 0 ? '[]\n' : `${yaml.dump(rows, { lineWidth: 0, noRefs: true })}`
  if (!isTrustPatch(body)) throw new Error('derived trust patch is not a loader patch list')
  return `${HEADER}\n${body}`
}

/**
 * Package directories under one node_modules root, scoped names included.
 * @param {string} modules - a node_modules directory.
 */
async function packageNames(modules) {
  const names = []
  for (const name of (await readdir(modules)).sort()) {
    if (name.startsWith('.')) continue
    if (name.startsWith('@')) {
      for (const child of (await readdir(join(modules, name))).sort()) {
        if (child.startsWith('.')) continue
        names.push(`${name}/${child}`)
      }
      continue
    }
    names.push(name)
  }
  return names
}

/**
 * The trust rows of every bundle under the roots a tenant's dsh resolves.
 *
 * Roots are read in resolution order and later roots override earlier ones by
 * entry id: the profile copy is the one dsh loads, so its bundle decides.
 * A bundle that cannot be read or parsed is skipped with a loud log — that
 * package keeps its own default rather than taking the whole launch down.
 * @param {string[]} roots - node_modules directories, first resolved last.
 * @returns {{ id: string, name: string, config: Record<string, unknown> }[]}
 */
export async function trustRowsForRoots(roots) {
  /** @type {Map<string, { id: string, name: string, config: Record<string, unknown> }>} */
  const byId = new Map()
  for (const modules of roots) {
    if (!existsSync(modules)) continue
    for (const name of await packageNames(modules)) {
      const bundlePath = join(modules, name, 'cordis.patch.yml')
      const text = await readFile(bundlePath, 'utf8').catch((error) => {
        // A package without a bundle layer declares nothing to restate.
        if (error.code !== 'ENOENT') {
          console.error(`deployment-trust: cannot read ${name} bundle:`, error?.message ?? error);
        }
        return undefined;
      })
      if (text === undefined) continue
      try {
        for (const row of trustRows(text, name)) byId.set(row.id, row)
      } catch (error) {
        console.error(`deployment-trust: ${error instanceof Error ? error.message : error}`);
      }
    }
  }
  // Deterministic order: one row per entry id, sorted, so an upgrade keeps
  // journal-routed settings changes aligned with their rows.
  return [...byId.values()].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
}

function handOver(path, uid, group) {
  return new Promise((resolve, reject) => {
    execFile('chown', [`${String(uid)}:${group}`, path], (error) => {
      if (error) reject(error);
      else resolve();
    });
  });
}

/**
 * Derive and write one tenant's trust overlay.
 *
 * Called on every launch after the plugin sync: image payload and tenant
 * installs alike are re-read, so an upgraded plugin is re-derived without a
 * gateway restart. No rows (or a disabled switch) remove any previous overlay
 * and launch without one.
 * @param {{
 *   home: string,
 *   jailHome: string,
 *   uid: number,
 *   linuxName: string,
 *   payloadModules?: string,
 *   profileModules?: string,
 *   layerModules?: string,
 * }} options - the tenant home in both views plus the node_modules roots to
 *   scan (all three default to what the image and the plugin sync stage).
 * @returns {Promise<{ patch?: string }>} the `--patch` argument, or nothing.
 */
export async function deploymentTrustPatch(options) {
  const { home, jailHome, uid, linuxName } = options;
  const path = join(home, PATCH_RELATIVE);
  if (process.env[TRUST_ENV] === 'false') {
    await rm(path, { force: true });
    return {};
  }
  const roots = [
    options.payloadModules ?? join(AGENT_PLUGIN_ROOT, 'node_modules'),
    options.layerModules ?? join(home, '.dsh', 'profiles', 'node_modules'),
    options.profileModules ?? join(home, '.dsh', 'profiles', 'web', 'node_modules'),
  ];
  const rows = await trustRowsForRoots(roots);
  if (rows.length === 0) {
    await rm(path, { force: true });
    return {};
  }
  const body = trustPatchDoc(rows);
  if (!isTrustPatch(body)) {
    // Refusing to hand over a document the launcher would reject is the only
    // way this module can be sure it never keeps a workspace down.
    console.error(`deployment-trust overlay refused for ${linuxName}: not a loader patch list`);
    return {};
  }
  try {
    await mkdir(dirname(path), { recursive: true, mode: 0o700 });
    await writeFile(path, body, { mode: 0o600 });
  } catch (error) {
    // A workspace that cannot boot is worse than one that lost a preference:
    // an unwritable overlay leaves the plugin on its own default.
    console.error(`deployment-trust overlay not written for ${linuxName}:`, error?.message ?? error);
    return {};
  }
  await handOver(path, uid, linuxName);
  return { patch: `${jailHome}/.dsh/profiles/web/trust.patch.yml` };
}

/**
 * Remove the overlay, so the next launch runs without it.
 * @param {{ home: string }} options - the tenant home the overlay lives in.
 * @returns {Promise<void>}
 */
export async function dropTrustPatch(options) {
  await rm(join(options.home, PATCH_RELATIVE), { force: true });
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [payloadRoot, out] = process.argv.slice(2);
  if (payloadRoot === undefined) {
    console.error('usage: node gateway/deployment-trust.mjs <payloadRoot> [out]');
    process.exit(2);
  }
  const rows = await trustRowsForRoots([join(payloadRoot, 'node_modules')]);
  for (const { id, name } of rows) {
    console.log(`deployment-trust: ${name} entry ${id} -> trusted-host`);
  }
  const doc = trustPatchDoc(rows);
  if (out === undefined) console.log(doc);
  else await writeFile(out, doc, { mode: 0o644 });
}
